"""Pack the dots_team export (manifest.json, today.bin, team.bin from export_dots.py in the robot repo) into dots_data.js,
so the page needs no fetch. Usage: python3 tools/pack_dots.py ~/Documents/projects/robot/docs/evidence/web/dots_team/data"""
import base64, json, os, sys
src = os.path.expanduser(sys.argv[1])
out = {"manifest": json.load(open(os.path.join(src, "manifest.json")))}
for k in ("today", "team"):
    out[k] = base64.b64encode(open(os.path.join(src, k + ".bin"), "rb").read()).decode()
dst = os.path.join(os.path.dirname(__file__), "..", "dots_data.js")
with open(dst, "w") as f:
    f.write("/* Generated by tools/pack_dots.py from export_dots.py output: manifest plus base64 int16 point and pose data. */\n")
    f.write("window.DOTS=" + json.dumps(out, separators=(",", ":")) + ";\n")
print(os.path.getsize(dst) // 1024, "KB ->", dst)
