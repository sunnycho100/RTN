"""Export a reconstructed scan to site/scan.js for the landing page animation.

Usage: python3 site/tools/export_scan.py SCAN_DIR [--points 14000]
SCAN_DIR holds lidar_map.ply (Open3D binary, x y z nx ny nz), poses.txt (camera-to-world 4x4 per line)
and mujoco/scene_info.json (from build_scene.py: leveling transform, wall boxes) plus mujoco/export/hull_*.obj.
Units in the output are centimeters, in the leveled frame (floor at z = 0, up = +z).
"""
import argparse, glob, json, os
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("scan_dir")
ap.add_argument("--points", type=int, default=14000)
ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "scan.js"))
args = ap.parse_args()

f = open(os.path.join(args.scan_dir, "lidar_map.ply"), "rb")
header = b""
while not header.endswith(b"end_header\n"):
    header += f.readline()
a = np.frombuffer(f.read(), dtype="<f8").reshape(-1, 6)
info = json.load(open(os.path.join(args.scan_dir, "mujoco", "scene_info.json")))
T = np.array(info["transform_from_scan"])
p = a[:, :3] @ T[:3, :3].T + T[:3, 3]
n = a[:, 3:] @ T[:3, :3].T

# Keep the built room: inside the scene footprint (plus a margin) and below the crop height.
lo = p.min(0)
sx, sy, _ = info["size_m"]
walls = info["walls"]
wx = [w["pos"][0] for w in walls]; wy = [w["pos"][1] for w in walls]
x0, x1, y0, y1 = min(wx) - 0.3, max(wx) + 0.3, min(wy) - 0.3, max(wy) + 0.3
keep = (p[:, 0] > x0) & (p[:, 0] < x1) & (p[:, 1] > y0) & (p[:, 1] < y1) & (p[:, 2] > -0.05) & (p[:, 2] < info["crop_height"])
p, n = p[keep], n[keep]

# Voxel downsample to about --points points (grow the voxel until it fits).
v = 0.02
while True:
    key = np.floor(p / v).astype(np.int64)
    _, idx = np.unique(key, axis=0, return_index=True)
    if len(idx) <= args.points:
        break
    v *= 1.1
p, n = p[idx], n[idx]
shade = np.clip(np.round(np.abs(n[:, 2]) * 9), 0, 9)  # 9 = horizontal surface (floor, tables)
pts = np.column_stack([np.round(p * 100), shade]).astype(int)

P = np.loadtxt(os.path.join(args.scan_dir, "poses.txt")).reshape(-1, 4, 4)
P = np.einsum("ij,njk->nik", T, P)[::3]
cams = np.column_stack([np.round(P[:, :3, 3] * 100), np.round(P[:, :3, 2] * 100)]).astype(int)

def box(w):
    return [round(w["pos"][0] * 100), round(w["pos"][1] * 100), round(w["pos"][2] * 100),
            round(w["half"][0] * 100), round(w["half"][1] * 100), round(w["half"][2] * 100), round(w["yaw"], 3)]

hulls = []  # clutter as axis-aligned boxes: enough for a line drawing
for path in sorted(glob.glob(os.path.join(args.scan_dir, "mujoco", "export", "hull_*.obj"))):
    vs = np.array([list(map(float, l.split()[1:4])) for l in open(path) if l.startswith("v ")])
    c, h = (vs.min(0) + vs.max(0)) / 2, (vs.max(0) - vs.min(0)) / 2
    hulls.append([*np.round(c * 100).astype(int).tolist(), *np.round(h * 100).astype(int).tolist(), 0])

data = {"voxel_cm": round(v * 100, 1), "pts": pts.ravel().tolist(), "cams": cams.ravel().tolist(),
        "walls": [box(w) for w in walls], "hulls": hulls,
        "spawn": [round(x * 100) for x in info["spawn_xy"]]}
with open(args.out, "w") as out:
    out.write("/* Generated by site/tools/export_scan.py from %s. Points [x,y,z,shade] in cm, cams [x,y,z,fx,fy,fz]. */\n"
              % os.path.basename(os.path.normpath(args.scan_dir)))
    out.write("window.SCAN=" + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"{len(pts)} points (voxel {v*100:.1f} cm), {len(cams)} cameras, {len(walls)} walls, {len(hulls)} hulls -> {args.out}")
